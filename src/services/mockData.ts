// ── Mock AI analyses ──────────────────────────────────────────
const makeAnalysis = (
  reportId: string,
  severity: number, urgency: number, frequency: number,
  community_impact: number, persistence: number,
  reasoning: string,
  category = 'Roads & Infrastructure',
  confidence = 0.89,
): AIAnalysis => {
  const raw = severity * 0.30 + urgency * 0.25 + frequency * 0.20 + community_impact * 0.15 + persistence * 0.10;
  const priority_score = Math.round(raw * 10);
  const priority_level = priority_score >= 75 ? 'CRITICAL' : priority_score >= 50 ? 'HIGH' : priority_score >= 25 ? 'MEDIUM' : 'LOW';
  return {
    id: `ai-${reportId}`,
    report_id: reportId,
    predicted_category: category,
    category_confidence: confidence,
    severity_score: severity,
    urgency_score: urgency,
    frequency_score: frequency,
    community_impact_score: community_impact,
    persistence_score: persistence,
    priority_score,
    priority_level,
    priority_breakdown: { severity, urgency, frequency, community_impact, persistence },
    reasoning,
    model_version: 'jd-nlp-v1.0',
    processed_at: new Date().toISOString(),
  };
};

